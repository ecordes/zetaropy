"""Build the site's HTML from src/ and templates/.

Source files hold only what is unique to a page: front matter, and the
content itself. Everything repeated -- the icon and font links, the
navbar, the footer, and for entries the whole page-header/article
scaffold -- lives once in templates/ and is pulled in here.

Anything one page can derive from another is computed rather than
written down twice: the journal list, the newest few on the home page,
each entry's prev/next links, and each gallery wing's work count (which
used to be kept by hand in three places and agree by luck).

    python3 bin/build.py           # write the site
    python3 bin/build.py --check   # exit 1 if the built HTML is stale

Output lands at the repo root on the same paths as before and is
committed, which is what keeps GitHub Pages serving plain files,
notify_posts.py able to read a post's markup, and `python3 -m
http.server` an honest preview. Never hand-edit the output -- the next
build overwrites it. Edit src/ or templates/.

Templates understand exactly two things, `{{ name }}` and
`{% include file.html %}`; anything needing a loop is assembled in
Python below, where it can be read.
"""

import glob
import html
import os
import re
import sys

os.chdir(os.path.join(os.path.dirname(__file__), ".."))

SITE_YEAR = "2026"
INDEX_KEEP = 3
WINGS = [("zeta", "01"), ("entropy", "02"), ("paradox", "03"), ("howl", "04")]

# Where the prev/next chain stops at either end.
OLDEST_PREV = ("../cats.html", "Meet the crew →")
NEWEST_NEXT = ("../journal.html", "← All entries")

SECTIONS = [("posts/", "journal"), ("cats/", "cats"), ("gallery/", "gallery"),
            ("journal.html", "journal"), ("cats.html", "cats"),
            ("gallery.html", "gallery"), ("index.html", "home")]


def read(path):
    return open(path, encoding="utf-8").read()


def generated_from(source):
    """The do-not-edit marker stamped into every built page."""
    return (f"GENERATED by bin/build.py from {source} -- edit that file, "
            "not this one, then run: python3 bin/build.py")


def esc(text):
    """Escape front-matter text for HTML. Quotes too -- some of these
    values land inside attributes -- but not apostrophes, which are fine
    in double-quoted attributes and would bloat ordinary prose."""
    return html.escape(text, quote=False).replace('"', "&quot;")


def front_matter(text):
    """Split a source file into its front matter dict and its body.

    Deliberately tiny: `key: value` lines between --- fences, with
    true/false read as booleans. `key: >` starts a block whose indented
    lines are kept as written -- prose keeps the line breaks its author
    chose rather than being re-wrapped by a machine.
    """
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 3)
    if end < 0:
        raise ValueError("front matter opens with --- but never closes")
    meta, key, block = {}, None, []
    for line in text[4:end].splitlines():
        if key and (line.startswith("  ") or not line.strip()):
            if line.strip():
                block.append(line.strip())
            continue
        if key:
            meta[key], key, block = block, None, []
        if ":" not in line or not line.strip():
            continue
        name, value = line.split(":", 1)
        value = value.strip()
        if value == ">":
            key = name.strip()
        else:
            meta[name.strip()] = {"true": True, "false": False}.get(value, value)
    if key:
        meta[key] = block
    return meta, text[end + 5:]


def render(template, values, where="template"):
    """Fill {% include %}, {{active:...}}, then {{ name }} -- in that
    order, so the name pass (which splices in whole page bodies) runs
    last and nothing ever re-scans spliced-in content. A post body may
    therefore contain literal {{ ... }} safely.

    An unknown {{ name }} stops the build naming the file, instead of
    silently rendering as nothing.
    """
    def include(m):
        return render(read(f"templates/includes/{m.group(1)}"), values,
                      f"templates/includes/{m.group(1)}").rstrip("\n")

    out = re.sub(r"\{%\s*include\s+([\w.-]+)\s*%\}", include, template)

    def active(m):
        return ' class="active"' if m.group(1) == values.get("section") else ""

    out = re.sub(r"\{\{active:(\w+)\}\}", active, out)

    def value(m):
        name = m.group(1)
        if name not in values:
            sys.exit(f"{where}: unknown placeholder {{{{ {name} }}}}")
        return str(values[name])

    return re.sub(r"\{\{\s*(\w+)\s*\}\}", value, out)


def section_of(path):
    for prefix, name in SECTIONS:
        if path.startswith(prefix):
            return name
    return None


def indent(text, spaces):
    pad = " " * spaces
    return "\n".join(pad + l if l.strip() else l for l in text.splitlines())


def long_date(name):
    """'2026-08-27-slug.html' -> '27 August 2026'."""
    import datetime as dt
    d = dt.date.fromisoformat(name[:10])
    return f"{d.day} {d.strftime('%B')} {d.year}"


def parse_source(path, required):
    """Front matter + body for one source file, with errors a person can
    act on: the raw ValueError/KeyError a typo used to produce named
    neither the file nor the problem."""
    try:
        meta, body = front_matter(read(path))
    except ValueError as e:
        sys.exit(f"{path}: {e}")
    missing = [k for k in required if k not in meta]
    if missing:
        sys.exit(f"{path}: front matter is missing {', '.join(missing)}")
    return meta, body


def load_posts():
    """Every entry, newest first, with its front matter and body."""
    posts = []
    for path in sorted(glob.glob("src/posts/*.html"), reverse=True):
        name = os.path.basename(path)
        meta, body = parse_source(
            path, ("title", "headline", "description", "blurb"))
        meta.update(name=name, body=body.strip("\n"), date=long_date(name))
        posts.append(meta)
    return posts


def listing(post, cell_indent, key="blurb"):
    """One <a class="post-item"> block for a journal or home-page list.

    The home page runs a shorter blurb than the journal where one is
    given, so `blurb_home` wins there and falls back to `blurb`.
    """
    date_line = post["date"] + (" · From the archive" if post.get("archive") else "")
    prose = indent(esc("\n".join(post.get(key) or post["blurb"])), 8).lstrip()
    block = f"""<a class="post-item" href="posts/{post['name']}">
    <span class="post-date">{date_line}</span>
    <h2>{esc(post['title'])}</h2>
    <p>
        {prose}
    </p>
</a>"""
    return indent(block, cell_indent)


def build_posts(posts, out):
    """Render each entry, wiring its chain links from its neighbours."""
    template = read("templates/post.html")
    for i, post in enumerate(posts):
        newer = posts[i - 1] if i > 0 else None
        older = posts[i + 1] if i + 1 < len(posts) else None

        next_href, next_label = ((newer["name"], f"← Next: {esc(newer['title'])}")
                                 if newer else NEWEST_NEXT)
        prev_href, prev_label = ((older["name"], f"Previous: {esc(older['title'])} →")
                                 if older else OLDEST_PREV)

        # Two lines with the second emphasised; a one-word headline (no
        # "|", or nothing after it) gets the single-span form instead of
        # an orphaned "<span>.</span>".
        first, _, rest = (esc(s) for s in post["headline"].partition("|"))
        headline_html = (f"{first.strip()}<br>\n"
                         f"                <span>{rest.strip()}.</span>"
                         if rest.strip() else f"<span>{first.strip()}.</span>")

        eyebrow = post["date"].upper() + (
            " · FROM THE ARCHIVE" if post.get("archive") else "")
        title = ("From the archive: " + post["title"][:1].lower() + post["title"][1:]
                 if post.get("archive") else post["title"])

        main = render(template, dict(
            content=indent(post["body"], 16), eyebrow=eyebrow,
            headline_html=headline_html,
            next_href=next_href, next_label=next_label,
            prev_href=prev_href, prev_label=prev_label),
            "templates/post.html").rstrip("\n")

        out[f"posts/{post['name']}"] = render(read("templates/base.html"), dict(
            page_title=f"{esc(title)} — Zetaropy",
            description=esc(post["description"]),
            generated=generated_from(f"src/posts/{post['name']}"),
            section="journal", body_class="", root="../", year=SITE_YEAR,
            content=main,
            scripts='    <script src="../js/main.js"></script>'),
            "templates/base.html")


def build_pages(posts, out):
    """Render the hand-made pages, filling in whatever is derivable."""
    counts = {cat: len(re.findall(r'class="placard-no"',
                                  read(f"src/pages/gallery/{cat}.html")))
              for cat, _ in WINGS}

    derived = {f"works_{cat}": str(n) for cat, n in counts.items()}
    derived["post_list"] = "\n\n".join(listing(p, 12) for p in posts)
    derived["recent_posts"] = "\n\n".join(
        listing(p, 16, "blurb_home") for p in posts[:INDEX_KEEP])

    for path in sorted(glob.glob("src/pages/**/*.html", recursive=True)):
        rel = os.path.relpath(path, "src/pages")
        meta, body = parse_source(path, ("description",))
        if "title" not in meta and "title_exact" not in meta:
            sys.exit(f"{path}: front matter needs title or title_exact")
        root = "" if os.path.dirname(rel) == "" else "../"
        body_class = meta.get("body_class", "")

        # The home page's title is the site name alone, with nothing
        # appended; every other page reads "<page> — Zetaropy".
        page_title = esc(meta.get("title_exact")
                         or f"{meta.get('title', '')} — Zetaropy")

        values = dict(derived, root=root, year=SITE_YEAR,
                      section=section_of(rel), page_title=page_title,
                      generated=generated_from(path),
                      # A wing's description quotes its own work count.
                      description=esc(render(meta["description"], derived, path)),
                      body_class=f' class="{body_class}"' if body_class else "",
                      scripts=indent("\n".join(
                          f'<script src="{root}js/{s}"></script>'
                          for s in meta.get("scripts", "main.js").split()), 4))
        values["content"] = render(body.strip("\n"), values, path)
        out[rel] = render(read("templates/base.html"), values,
                          "templates/base.html")


def build():
    posts = load_posts()
    out = {}
    build_posts(posts, out)
    build_pages(posts, out)
    return out


def orphans(pages):
    """Built files whose source is gone. posts/, cats/ and gallery/ are
    wholly generated, so an .html there that the build did not produce
    is a leftover -- without this, deleting a source would leave its old
    page served forever. The repo root is shared territory (a future
    hand-placed 404.html, say) and is left alone."""
    on_disk = (glob.glob("posts/*.html") + glob.glob("cats/*.html")
               + glob.glob("gallery/*.html"))
    return sorted(set(on_disk) - set(pages))


def stale_pages(pages):
    return [p for p in sorted(pages)
            if not os.path.exists(p) or read(p) != pages[p]]


def write_pages(pages):
    """Bring the output tree in line with `pages`: write what changed,
    remove what no longer has a source. Returns (written, removed)."""
    written = stale_pages(pages)
    for path in written:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        open(path, "w", encoding="utf-8").write(pages[path])
    removed = orphans(pages)
    for path in removed:
        os.remove(path)
    return written, removed


if __name__ == "__main__":
    pages = build()

    if "--check" in sys.argv:
        stale = stale_pages(pages)
        extra = orphans(pages)
        for p in stale:
            print(f"stale: {p}")
        for p in extra:
            print(f"no source builds it: {p}")
        if stale or extra:
            print("\nRun: python3 bin/build.py")
            sys.exit(1)
        print(f"All {len(pages)} pages are up to date with src/.")
        sys.exit(0)

    written, removed = write_pages(pages)
    for p in written:
        print(f"wrote   {p}")
    for p in removed:
        print(f"removed {p} (no source builds it)")
    if not written and not removed:
        print(f"All {len(pages)} pages already current. Nothing to do.")
